/* Service worker: file aplikasi jaringan-dulu (selalu versi terbaru), cache saat offline. API tidak pernah di-cache. */
var CACHE = 'aiueo-shell-v7';
var SHELL = ['/', '/index.html', '/app.js', '/api-client.js', '/config.js', '/qr.js', '/manifest.webmanifest', '/logo.png', '/logo-sm.png', '/icon-192.png'];
self.addEventListener('install', function (e) {
  e.waitUntil(caches.open(CACHE).then(function (c) { return c.addAll(SHELL); }).then(function () { return self.skipWaiting(); }));
});
self.addEventListener('activate', function (e) {
  e.waitUntil(caches.keys().then(function (ks) {
    return Promise.all(ks.filter(function (k) { return k !== CACHE; }).map(function (k) { return caches.delete(k); }));
  }).then(function () { return self.clients.claim(); }));
});
self.addEventListener('fetch', function (e) {
  var r = e.request;
  if (r.method !== 'GET' || new URL(r.url).origin !== self.location.origin) return;
  e.respondWith(fetch(r).then(function (res) {
    if (res && res.ok) { var cp = res.clone(); caches.open(CACHE).then(function (c) { c.put(r, cp); }); }
    return res;
  }).catch(function () { return caches.match(r).then(function (m) { return m || caches.match('/index.html'); }); }));
});
